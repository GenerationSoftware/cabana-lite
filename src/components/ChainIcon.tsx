import { CHAIN_ICON, NETWORK } from '../lib/constants'

type ChainIconProps = {
  chainId: number
  className?: string
}

export const ChainIcon = ({ chainId, className = 'h-5 w-5' }: ChainIconProps) => {
  if (chainId === NETWORK.base || chainId === NETWORK.base_sepolia) {
    return <BaseIcon className={className} />
  }

  if (chainId === NETWORK.scroll || chainId === NETWORK.scroll_sepolia) {
    return <ScrollIcon className={className} />
  }

  if (chainId === NETWORK.gnosis || chainId === NETWORK.gnosis_chiado) {
    return <GnosisIcon className={className} />
  }

  if (chainId === NETWORK.world) {
    return <WorldIcon className={className} />
  }

  const iconSrc = CHAIN_ICON[chainId]

  if (iconSrc) {
    return <img src={iconSrc} alt="" className={className} />
  }

  return (
    <span
      className={`${className} flex items-center justify-center rounded-full bg-pt-purple-500 font-grotesk text-xs font-semibold text-white`}
    >
      ?
    </span>
  )
}

